import type { DailyLog, JournalEntry, Settings } from "@/types";
import { deriveCycles } from "@/lib/cycle/engine";
import { symptomLabel } from "@/lib/constants";
import { b64ToBytes, bytesToB64, deriveKey, decryptText, encryptText, KDF_ITERATIONS, randomBytes } from "@/lib/crypto";

export const EXPORT_VERSION = "1.0";
export const APP_VERSION = "1.0.0";

export interface BackupJson {
  exportVersion: string;
  exportedAt: string;
  appVersion: string;
  dailyLogs: DailyLog[];
  journals: JournalEntry[];
  settings?: Partial<Settings>;
}

export function buildBackup(
  dailyLogs: DailyLog[],
  journals: JournalEntry[],
  settings: Settings,
): BackupJson {
  return {
    exportVersion: EXPORT_VERSION,
    exportedAt: new Date().toISOString(),
    appVersion: APP_VERSION,
    dailyLogs,
    journals,
    settings: scrubSettings(settings),
  };
}

export function downloadBackup(backup: BackupJson): void {
  const blob = new Blob([JSON.stringify(backup, null, 2)], { type: "application/json" });
  triggerDownload(blob, `lantern-backup-${new Date().toISOString().slice(0, 10)}.json`);
}

/** CSV: cycle history (start, period days, length) and daily logs. */
export function buildCSV(dailyLogs: DailyLog[]): string {
  const cycles = deriveCycles(dailyLogs);
  const lines: string[] = [];
  lines.push("CSV produced by Lantern");
  lines.push("");
  lines.push("Cycles");
  lines.push("Cycle,Start,End,PeriodDays,CycleLength");
  cycles.forEach((c, i) => {
    lines.push(`${i + 1},${c.start},${c.end ?? ""},${c.periodDuration ?? ""},${c.cycleLength ?? ""}`);
  });
  lines.push("");
  lines.push("Daily logs");
  lines.push("Date,flow,moods,symptoms,energy,stress");
  for (const l of dailyLogs.slice().sort((a, b) => a.date.localeCompare(b.date))) {
    lines.push(`${l.date},${l.flow},"${l.moods.join("|")}","${l.symptoms.join("|")}",${l.energy ?? ""},${l.stress ?? ""}`);
  }
  return lines.join("\n");
}

export function downloadCSV(dailyLogs: DailyLog[]): void {
  const blob = new Blob([buildCSV(dailyLogs)], { type: "text/csv;charset=utf-8" });
  triggerDownload(blob, `lantern-history-${new Date().toISOString().slice(0, 10)}.csv`);
}

/** Plain-language summary for the user to bring to a professional. Neutral. */
export function buildDoctorSummary(
  dailyLogs: DailyLog[],
  journals: JournalEntry[],
  settings: Settings,
): string {
  const cycles = deriveCycles(dailyLogs);
  const lengths = cycles.map((c) => c.cycleLength).filter((v): v is number => v !== undefined);
  const durations = cycles.map((c) => c.periodDuration).filter((v): v is number => v !== undefined);
  const lines: string[] = [];
  lines.push("My cycle summary (generated by Lantern)");
  lines.push(`Generated: ${new Date().toISOString()}`);
  lines.push(`App version: ${APP_VERSION}`);
  lines.push("");
  lines.push(`Number of logged cycles: ${cycles.length}`);
  if (lengths.length) lines.push(`Cycle lengths (days): ${lengths.join(", ")}`);
  if (durations.length) lines.push(`Period durations (days): ${durations.join(", ")}`);
  if (settings.typicalCycleLength) lines.push(`Usual cycle length set in app: ${settings.typicalCycleLength} days`);

  // symptom frequencies
  const symptomCounts = new Map<string, number>();
  for (const l of dailyLogs) for (const s of l.symptoms) symptomCounts.set(s, (symptomCounts.get(s) ?? 0) + 1);
  if (symptomCounts.size) {
    lines.push("");
    lines.push("Frequency of logged symptoms:");
    for (const [s, n] of [...symptomCounts.entries()].sort((a, b) => b[1] - a[1])) {
      lines.push(`- ${symptomLabel(s, settings.customItems)}: ${n} day${n === 1 ? "" : "s"}`);
    }
  }
  lines.push("");
  lines.push("Note: These are calendar-style logs a person recorded. They are not a diagnosis.");
  return lines.join("\n");
}

export function downloadDoctorSummary(
  dailyLogs: DailyLog[],
  journals: JournalEntry[],
  settings: Settings,
): void {
  const blob = new Blob([buildDoctorSummary(dailyLogs, journals, settings)], {
    type: "text/plain;charset=utf-8",
  });
  triggerDownload(blob, `lantern-cycle-summary-${new Date().toISOString().slice(0, 10)}.txt`);
}

function scrubSettings(s: Settings): Partial<Settings> {
  return {
    typicalCycleLength: s.typicalCycleLength,
    typicalPeriodDuration: s.typicalPeriodDuration,
    regularity: s.regularity,
    firstDayOfWeek: s.firstDayOfWeek,
    notificationPrivacy: s.notificationPrivacy,
  };
}

function triggerDownload(blob: Blob, filename: string): void {
  const url = URL.createObjectURL(blob);
  const a = document.createElement("a");
  a.href = url;
  a.download = filename;
  document.body.appendChild(a);
  a.click();
  a.remove();
  URL.revokeObjectURL(url);
}

/* ------------------------------------------------------------------ */
/* Encrypted (password-protected) backups.                             */
/*                                                                     */
/* The same PBKDF2 → AES-256-GCM pipeline used for at-rest encryption  */
/* seals the whole backup so a file on a drive or in a cloud folder    */
/* can't be read without the password. The password is never stored.   */
/* ------------------------------------------------------------------ */

export const ENCRYPTED_BACKUP_KIND = "lantern:encrypted:v1";

export interface EncryptedBackup {
  kind: typeof ENCRYPTED_BACKUP_KIND;
  salt: string; // base64
  iterations: number;
  iv: string; // base64
  data: string; // base64 ciphertext of the BackupJson
}

/** Encrypt a backup into a self-contained, password-protected payload. */
export async function encryptBackup(backup: BackupJson, password: string): Promise<EncryptedBackup> {
  const salt = randomBytes(16);
  const key = await deriveKey(password, salt, KDF_ITERATIONS);
  const blob = await encryptText(key, JSON.stringify(backup));
  return {
    kind: ENCRYPTED_BACKUP_KIND,
    salt: bytesToB64(salt),
    iterations: KDF_ITERATIONS,
    iv: blob.iv,
    data: blob.data,
  };
}

/** Decrypt a password-protected backup. Returns null on wrong password or tampering. */
export async function decryptBackup(payload: EncryptedBackup, password: string): Promise<BackupJson | null> {
  try {
    const key = await deriveKey(password, b64ToBytes(payload.salt), payload.iterations);
    const text = await decryptText(key, { iv: payload.iv, data: payload.data });
    if (!text) return null;
    const parsed = JSON.parse(text) as BackupJson;
    if (!parsed || typeof parsed !== "object" || !Array.isArray(parsed.dailyLogs) || !Array.isArray(parsed.journals)) {
      return null;
    }
    return parsed;
  } catch {
    return null;
  }
}

export function downloadEncryptedBackup(payload: EncryptedBackup): void {
  const blob = new Blob([JSON.stringify(payload)], { type: "application/json" });
  triggerDownload(blob, `lantern-backup-${new Date().toISOString().slice(0, 10)}.lantern.json`);
}

export type BackupFileKind = "plain" | "encrypted" | "unknown";

/** Cheap sniff so the import flow can ask for a password when needed. */
export function sniffBackup(text: string): BackupFileKind {
  try {
    const parsed = JSON.parse(text);
    if (parsed && typeof parsed === "object" && parsed.kind === ENCRYPTED_BACKUP_KIND) return "encrypted";
    if (parsed && typeof parsed === "object" && Array.isArray(parsed.dailyLogs)) return "plain";
    return "unknown";
  } catch {
    return "unknown";
  }
}